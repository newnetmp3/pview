const assert=require('node:assert/strict');
const vm=require('node:vm');
const fs=require('node:fs');
const path=require('node:path');
const context=vm.createContext({URL,BigInt,Uint8Array,console,Blob});
const dir=path.join(__dirname,'..');
for(const file of ['shared.js','hls.js']) vm.runInContext(fs.readFileSync(path.join(dir,file),'utf8'),context);
const get=(script)=>vm.runInContext(script,context);
assert.equal(get('PH.isPornhex("https://pornhex.com/video/a")'),true);
assert.equal(get('PH.isPornhex("https://foo.pornhex.com/a")'),true);
assert.equal(get('PH.isPornhex("https://pornhex.com.evil.test/a")'),false);
assert.equal(get('PH.classify("https://cdn.test/v.mp4?token=x")'),'video');
assert.equal(get('PH.classify("https://cdn.test/file", "application/vnd.apple.mpegurl")'),'hls');
assert.equal(get('PH.classify("https://cdn.test/file.ts")'),null);
assert.equal(get('PH.quality("https://cdn.test/720p/index.m3u8")'),'720p');
assert.equal(get('PH.cleanTitle("Hello | Pornhex")'),'Hello');
const master=`#EXTM3U\n#EXT-X-MEDIA:TYPE=AUDIO,GROUP-ID="a",URI="audio/a.m3u8"\n#EXT-X-STREAM-INF:BANDWIDTH=500000,RESOLUTION=640x360,AUDIO="a"\nlow/index.m3u8\n#EXT-X-STREAM-INF:BANDWIDTH=3200000,RESOLUTION=1920x1080,AUDIO="a"\nhigh/index.m3u8`;
const parsed=get('HLS.parse') // can't transfer? yes function context
const parsedMaster=parsed(master,'https://example.test/master.m3u8');
assert.equal(parsedMaster.variants.length,2);
assert.equal(parsedMaster.variants[1].resolution,'1920x1080');
assert.equal(parsedMaster.separateAudio,true);
assert.equal(get('HLS.bestVariant')(parsedMaster.variants).resolution,'1920x1080');
const media=`#EXTM3U\n#EXT-X-MEDIA-SEQUENCE:10\n#EXT-X-KEY:METHOD=AES-128,URI="key.bin",IV=0x0000000000000000000000000000000a\n#EXTINF:5.0,\n000.ts\n#EXT-X-BYTERANGE:100@250\n#EXTINF:5.0,\n001.ts\n#EXT-X-ENDLIST`;
const p=parsed(media,'https://example.test/sub/index.m3u8');
assert.equal(p.segments.length,2);
assert.equal(p.segments[0].sequence,10);
assert.equal(p.segments[1].sequence,11);
assert.equal(p.segments[1].range.start,250);
assert.equal(p.segments[0].key.url,'https://example.test/sub/key.bin');
assert.equal(p.isLive,false);
assert.equal(get('HLS.ivBytes')(null,1)[15],1);
console.log('PASS: URL safety, media classification, title cleanup, HLS master/media, byteranges, AES IV');
